# Alternative views of one read: map inline schema names to meaningful response types.
INLINE_NAMES_FOR_VIEWS = {
    "ListEvaluationRolloutsResponse0": "EvaluationRolloutPage",
    "ListEvaluationRolloutsResponse1": "EvaluationRolloutSummary",
}


def compress_catalog(payload: bytes) -> bytes:
    """Package the generated catalog with a portable gzip header."""
    buffer = io.BytesIO()
    with gzip.GzipFile(fileobj=buffer, filename="", mode="wb", mtime=0) as archive:
        archive.write(payload)
    return buffer.getvalue()


def render_operations(
    ops: Mapping[str, JSONObject],
    *,
    contract_version: str,
    contract_major: int,
) -> str:
    """Render generated operation descriptors while keeping defaults concise."""
    defaults: dict[str, JsonValue] = {
        "auth": True,
        "binary": False,
        "idempotent": False,
        "nullable_response": False,
        "path_params": [],
        "query_params": [],
        "request_model": None,
        "response_model": None,
    }
    preamble = f"""# Generated by scripts/gen_contract.py; do not edit.
from collections.abc import Sequence
from typing import TypedDict

CONTRACT_VERSION: str = {contract_version!r}
CONTRACT_MAJOR: int = {contract_major!r}

class Operation(TypedDict):
    method: str
    path: str
    scope: str
    path_params: list[str]
    query_params: list[str]
    idempotent: bool
    retry: str
    idempotency: str
    request_model: str | None
    response_model: str | None
    binary: bool
    nullable_response: bool
    auth: bool

def _operation(
    *, method: str, path: str, scope: str, retry: str, idempotency: str,
    auth: bool = True, binary: bool = False, idempotent: bool = False,
    nullable_response: bool = False, path_params: Sequence[str] = (),
    query_params: Sequence[str] = (), request_model: str | None = None,
    response_model: str | None = None,
) -> Operation:
    return {{
        "auth": auth,
        "binary": binary,
        "idempotency": idempotency,
        "idempotent": idempotent,
        "method": method,
        "nullable_response": nullable_response,
        "path": path,
        "path_params": list(path_params),
        "query_params": list(query_params),
        "request_model": request_model,
        "response_model": response_model,
        "retry": retry,
        "scope": scope,
    }}

OPERATIONS: dict[str, Operation] = {{
"""
    lines = [preamble.rstrip()]
    for name, op in sorted(ops.items()):
        lines.append(f"    {name!r}: _operation(")
        lines.extend(
            f"        {key}={value!r},"
            for key, value in sorted(op.items())
            if key not in defaults or value != defaults[key]
        )
        lines.append("    ),")
    return "\n".join([*lines, "}", ""])


def _resolve_ref(doc: JSONObject, value: JSONObject) -> JSONObject:
    if "$ref" in value:
        resolved = doc
        for part in value.text("$ref")[2:].split("/"):
            resolved = resolved.object(part)
        return resolved
    return value


def _flatten_schema(
    doc: JSONObject, json_object_cls: type[JSONObject], schema: JSONObject
) -> JSONObject:
    if "allOf" not in schema:
        return schema
    merged = json_object_cls({key: value for key, value in schema.items() if key != "allOf"})
    properties = dict(schema.object("properties", optional=True))
    required = schema.strings("required", optional=True)
    conditions: list[JsonValue] = []
    for part in schema.object_array("allOf"):
        if "if" in part:
            conditions.append(part)
            continue
        part = _flatten_schema(doc, json_object_cls, _resolve_ref(doc, part))
        for key, value in part.object("properties", optional=True).items():
            if key in properties and properties[key] != value:
                raise ValueError(f"conflicting allOf property: {key}")
            properties[key] = value
        required.extend(part.strings("required", optional=True))
        conditions.extend(part.array("allOf", optional=True))
        for key, value in part.items():
            if key not in {"properties", "required", "allOf"}:
                merged.setdefault(key, value)
    merged.update(type="object", properties=properties, required=list(dict.fromkeys(required)))
    if conditions:
        merged["allOf"] = conditions
    return merged


def _collect_operations(
    doc: JSONObject, schemas: dict[str, JSONObject], json_object_cls: type[JSONObject]
) -> dict[str, JSONObject]:
    ops: dict[str, JSONObject] = {}
    for path, item in doc.objects("paths").items():
        if not path.startswith("/v1/") and not any(
            isinstance(op, dict) and "x-synth-mcp-name" in op for op in item.values()
        ):
            continue
        for method, raw_op in item.items():
            if method not in {"get", "post", "put", "patch", "delete", "head", "options", "trace"}:
                continue
            op = json_object_cls.require(raw_op)
            if op.get("x-synth-status") != "implemented":
                continue
            oid = op.text("operationId")
            parameters = [
                _resolve_ref(doc, p) for p in op.object_array("parameters", optional=True)
            ]
            req = None
            if "requestBody" in op:
                body = (
                    _resolve_ref(doc, op.object("requestBody"))
                    .object("content")
                    .object("application/json")
                    .object("schema")
                )
                req = body.text("$ref", "").split("/")[-1]
                if not req:
                    req = oid[0].upper() + oid[1:] + "Request"
                    schemas[req] = body
            result = None
            nullable = False
            binary = False
            for status, resp in op.objects("responses").items():
                if not status.startswith("2"):
                    continue
                resolved = _resolve_ref(doc, resp)
                content = resolved.object("content", optional=True)
                if "application/json" in content:
                    schema = content.object("application/json").object("schema")
                    branches = schema.object_array("oneOf", optional=True)
                    refs = [b for b in branches if "$ref" in b]
                    nulls = [b for b in branches if b.get("type") == "null"]
                    views = [b for b in branches if b.get("type") == "object"]
                    if branches and len(views) == len(branches) >= 2:
                        if not all(
                            oid[0].upper() + oid[1:] + "Response" + str(i) in INLINE_NAMES_FOR_VIEWS
                            for i in range(len(views))
                        ):
                            raise ValueError(oid + ": name every view of its oneOf response")
                    elif branches:
                        if len(refs) != 1 or len(nulls) != 1 or len(branches) != 2:
                            raise ValueError(oid + ": unsupported oneOf response")
                        schema, nullable = refs[0], True
                    result = schema.text("$ref", "").split("/")[-1]
                    if not result:
                        result = oid[0].upper() + oid[1:] + "Response"
                        schemas[result] = schema
                elif content:
                    binary = True
                break
            ops[oid] = json_object_cls(
                {
                    "method": method.upper(),
                    "path": path,
                    "scope": op.text("x-synth-scope"),
                    "path_params": [p.text("name") for p in parameters if p["in"] == "path"],
                    "query_params": [p.text("name") for p in parameters if p["in"] == "query"],
                    "idempotent": op["x-synth-idempotency-key"],
                    "retry": op["x-synth-retry"],
                    "idempotency": op["x-synth-idempotency"],
                    "request_model": req,
                    "response_model": result,
                    "binary": binary,
                    "nullable_response": nullable,
                    "auth": op.get("security") != [],
                }
            )
    return ops


def _lift_all_schemas(
    schemas: dict[str, JSONObject], json_object_cls: type[JSONObject]
) -> dict[str, JSONObject]:
    inline_names = {
        **INLINE_NAMES_FOR_VIEWS,
        "LaunchRequestInputs": "RunInputs",
        "OptimizerRequest1": "OptimizerPin",
        "RunInputsFilesItem": "InputFile",
        "UploadPut": "UploadGrant",
        "RunTaskPageItemsItem": "RunTask",
        "OwnerResourceRequestSelection": "PoolSelection",
    }

    def lift(schema: JSONObject, name: str) -> JSONObject:
        schema = json_object_cls(schema)
        if schema.get("type") == "object" and len(schema.array("oneOf", optional=True)) == 1:
            branch = schema.object_array("oneOf")[0]
            del schema["oneOf"]
            schema["properties"] = {
                key: json_object_cls(
                    {
                        **value,
                        **branch.object("properties", optional=True).object(key, optional=True),
                    }
                )
                for key, value in schema.objects("properties", optional=True).items()
            }
        branches = schema.object_array("oneOf", optional=True)
        declared = schema.objects("properties", optional=True)
        if (
            schema.get("type") == "object"
            and len(branches) > 1
            and all(
                branch.keys() <= {"properties", "not"}
                and branch.object("properties", optional=True).keys() <= declared.keys()
                for branch in branches
            )
        ):
            del schema["oneOf"]
        if "properties" in schema:
            schema["properties"] = {
                key: lift_child(value, name + "".join(part.title() for part in key.split("_")))
                for key, value in schema.objects("properties").items()
            }
        if "items" in schema:
            schema["items"] = lift_child(schema.object("items"), name + "Item")
        for variant in ("oneOf", "anyOf"):
            if variant in schema:
                schema[variant] = [
                    lift_child(v, name + str(i)) for i, v in enumerate(schema.object_array(variant))
                ]
        return schema

    def lift_child(schema: JSONObject, name: str) -> JSONObject:
        name = inline_names.get(name, name)
        types = schema.get("type", [])
        closed_empty = types == "object" and schema.get("additionalProperties") is False
        if ("properties" in schema or closed_empty) and (
            types == "object" or (isinstance(types, list) and "object" in types)
        ):
            if "properties" not in schema:
                schema["properties"] = {}
            nullable = isinstance(types, list) and "null" in types
            schemas[name] = lift(json_object_cls({**schema, "type": "object"}), name)
            ref = json_object_cls({"$ref": "#/components/schemas/" + name})
            return json_object_cls({"anyOf": [ref, {"type": "null"}]}) if nullable else ref
        return lift(schema, name)

    for name in list(schemas):
        schemas[name] = lift(schemas[name], name)
    return schemas


_OPEN_MCP_CATALOG_FIELDS = frozenset({"pack_id", "plan_id", "topology"})


def _widen_mcp_catalog_enums(value: JsonValue, *, field: str | None = None) -> JsonValue:
    """Allow forward-compatible server catalog IDs in MCP request validation (SYN-6038)."""
    if isinstance(value, list):
        return [_widen_mcp_catalog_enums(item) for item in value]
    if isinstance(value, dict):
        updated: dict[str, JsonValue] = {}
        for key, item in value.items():
            if key == "properties" and isinstance(item, dict):
                updated[key] = {
                    prop: _widen_mcp_catalog_enums(prop_schema, field=prop)
                    for prop, prop_schema in item.items()
                }
            else:
                updated[key] = _widen_mcp_catalog_enums(item)
        if (
            field in _OPEN_MCP_CATALOG_FIELDS
            and updated.get("type") == "string"
            and "enum" in updated
        ):
            updated.pop("enum")
            updated.setdefault("minLength", 1)
        return updated
    return value


def _render_mcp_catalog(
    doc: JSONObject,
    root: Path,
    json_object_cls: type[JSONObject],
) -> tuple[list[JSONObject], str, str, bytes, str]:
    catalog = json_object_cls.parse(json.loads((root / "contracts/mcp-tools.json").read_text()))

    def expand(value: JsonValue) -> JsonValue:
        if isinstance(value, list):
            return [expand(v) for v in value]
        if isinstance(value, dict):
            if "$ref" in value:
                value = {
                    **_resolve_ref(doc, json_object_cls.require(value)),
                    **{k: v for k, v in value.items() if k != "$ref"},
                }
            return {k: expand(v) for k, v in value.items()}
        return value

    expected_tools: list[JSONObject] = []
    for _path, item in doc.objects("paths").items():
        for operation in item.values():
            if (
                not isinstance(operation, json_object_cls)
                or "x-synth-mcp-name" not in operation
                or operation.get("x-synth-status") != "implemented"
            ):
                continue
            params = [
                _resolve_ref(doc, p) for p in operation.object_array("parameters", optional=True)
            ]
            properties: dict[str, JsonValue] = {
                p.text("name"): expand(p["schema"]) for p in params if p["in"] in ("path", "query")
            }
            required: list[JsonValue] = [
                p.text("name")
                for p in params
                if p["in"] in ("path", "query") and p.flag("required")
            ]
            for narrowed in operation.array("x-synth-mcp-required", optional=True):
                if narrowed not in properties:
                    raise ValueError("x-synth-mcp-required names an unknown query parameter")
                if narrowed not in required:
                    required.append(narrowed)
            if "requestBody" in operation:
                body = operation.object("requestBody")
                properties["body"] = _widen_mcp_catalog_enums(
                    expand(body.object("content").object("application/json")["schema"])
                )
                if body.flag("required"):
                    required.append("body")
            if any(p["name"] == "Idempotency-Key" for p in params):
                properties["idempotency_key"] = {"type": "string", "minLength": 1, "maxLength": 128}
                required.append("idempotency_key")
            result_kind = operation.get("x-synth-mcp-result")
            expected_tools.append(
                json_object_cls(
                    {
                        "name": operation["x-synth-mcp-name"],
                        "description": operation["summary"],
                        "scope": operation["x-synth-scope"],
                        "access": operation.get("x-synth-mcp-access", "scoped"),
                        **({"result": result_kind} if result_kind is not None else {}),
                        "operationId": operation["operationId"],
                        "inputSchema": {
                            "type": "object",
                            "properties": properties,
                            "required": required,
                            "additionalProperties": False,
                        },
                    }
                )
            )
    tool_values: list[JsonValue] = list(expected_tools)
    catalog["tools"] = tool_values
    tool_payload = json.dumps(tool_values, sort_keys=True, separators=(",", ":")).encode()
    tools = (
        "# Generated by scripts/gen_contract.py; do not edit.\n"
        "import gzip\nfrom importlib.resources import files\n"
        "from typing import Literal, NotRequired\nfrom typing_extensions import TypedDict\nfrom pydantic import JsonValue, TypeAdapter\n"
        "class ToolSchema(TypedDict):\n    type: str\n    properties: dict[str, JsonValue]\n    required: list[str]\n    additionalProperties: bool\n"
        "class ToolDefinition(TypedDict):\n    name: str\n    description: str\n    scope: str\n    access: Literal['public', 'scoped']\n    result: NotRequired[Literal['McpOutputContent']]\n    operationId: str\n    inputSchema: ToolSchema\n"
        "TOOLS: list[ToolDefinition] = TypeAdapter(list[ToolDefinition]).validate_json("
        "gzip.decompress(files('synth_ai.mcp').joinpath('tools.json.gz').read_bytes()), strict=True)\n"
    )
    docs = (
        "# MCP tools\n\nGenerated from the pinned public OpenAPI and hosted catalog.\n\n| Tool | Operation | Scope |\n| --- | --- | --- |\n"
        + "".join(
            "| " + t.text("name") + " | " + t.text("operationId") + " | " + t.text("scope") + " |\n"
            for t in expected_tools
        )
    )
    return (
        expected_tools,
        json.dumps(catalog, indent=2, sort_keys=True) + "\n",
        tools,
        compress_catalog(tool_payload),
        docs,
    )


def prepare_contract(
    root: Path, spec: Path, json_object_cls: type[JSONObject]
) -> tuple[JSONObject, dict[str, JSONObject], dict[str, JSONObject]]:
    """Verify the OpenAPI pin hash and return parsed document, lifted schemas, and operations."""
    pin = tomllib.loads((root / "contracts/SOURCE.toml").read_text())
    if pin["sha256"] != hashlib.sha256(spec.read_bytes()).hexdigest():
        raise ValueError("contract pin hash mismatch")
    doc = json_object_cls.parse(yaml.safe_load(spec.read_text()))
    schemas = doc.object("components").objects("schemas")
    ops = _collect_operations(doc, schemas, json_object_cls)
    schemas = {n: _flatten_schema(doc, json_object_cls, s) for n, s in schemas.items()}
    return doc, _lift_all_schemas(schemas, json_object_cls), ops


def finalize_contract_outputs(
    root: Path,
    doc: JSONObject,
    schemas: dict[str, JSONObject],
    ops: Mapping[str, JSONObject],
    models_py: str,
    json_object_cls: type[JSONObject],
) -> dict[Path, str | bytes]:
    """Emit all remaining contract outputs and format generated Python modules."""
    info = doc.object("info")
    contract_version = info.text("version").strip()
    major_part = contract_version.split(".", 1)[0]
    if not major_part.isdigit() or int(major_part) < 1:
        raise ValueError(f"invalid OpenAPI info.version: {contract_version!r}")
    operations = render_operations(
        ops,
        contract_version=contract_version,
        contract_major=int(major_part),
    )
    _, catalog_json, tools_py, tools_gz, docs = _render_mcp_catalog(doc, root, json_object_cls)
    registry = doc.object_array("x-synth-scope-registry")
    requirements = schemas["LaunchRequest"].object("x-synth-profile-requirements")
    policy_source = "".join(
        [
            "# Generated by scripts/gen_contract.py; do not edit.\n",
            "SDK_OAUTH_SCOPES = "
            + repr(tuple(s.text("name") for s in registry if s.flag("sdk")))
            + "\n",
            "MESSAGE_MAX_BYTES = "
            + str(
                schemas["LaunchRequest"].object("properties").object("message")["x-synth-max-bytes"]
            )
            + "\n",
            "MCP_OUTPUT_CONTENT_MAX_BYTES = "
            + str(schemas["McpOutputContent"].object("properties").object("byte_size")["maximum"])
            + "\n",
            "PROFILE_REQUIRES_RESEARCH_TASK = "
            + repr({name: requirements.flag(name) for name in sorted(requirements)})
            + "\n",
            "DEFAULT_RUN_PROFILE = "
            + repr(schemas["LaunchRequest"].text("x-synth-default-profile"))
            + "\n",
        ]
    )
    version = tomllib.loads((root / "pyproject.toml").read_text())["project"]["version"]
    outputs: dict[Path, str | bytes] = {
        root / "synth_ai/_generated/policy.py": policy_source,
        root
        / "synth_ai/_version.py": f"# Generated from pyproject.toml; do not edit.\n__version__ = {version!r}\n",
        root / "contracts/mcp-tools.json": catalog_json,
        root / "synth_ai/_generated/models.py": models_py,
        root / "synth_ai/_generated/operations.py": operations,
        root / "synth_ai/mcp/tools.py": tools_py,
        root / "synth_ai/mcp/tools.json.gz": tools_gz,
        root / "docs/mcp-tools.md": docs,
    }
    for path, source in list(outputs.items()):
        if path.suffix == ".py":
            assert isinstance(source, str)
            fixed = subprocess.run(
                [
                    "ruff",
                    "check",
                    "--select",
                    "I,RUF036,E713",
                    "--fix",
                    "--stdin-filename",
                    str(path),
                    "-",
                ],
                input=source,
                text=True,
                capture_output=True,
                check=True,
            ).stdout
            outputs[path] = subprocess.run(
                ["ruff", "format", "--stdin-filename", str(path), "-"],
                input=fixed,
                text=True,
                capture_output=True,
                check=True,
            ).stdout
    return outputs
