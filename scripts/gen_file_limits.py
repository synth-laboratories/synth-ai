"""Generate transfer bounds from Core's pinned canonical file limits."""

from __future__ import annotations

import argparse
import hashlib
import json
import tomllib
from pathlib import Path
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field

ROOT = Path(__file__).resolve().parents[1]
Positive = Annotated[int, Field(gt=0)]


class FileLimits(BaseModel):
    model_config = ConfigDict(strict=True, frozen=True, extra="forbid")
    schema_version: Literal["synth.file-limits.v1"] = Field(alias="schema")
    file_max_bytes: Positive
    launch_max_bytes: Positive
    launch_max_files: Positive
    manifest_max_bytes: Positive
    inline_content_max_bytes: Positive
    name_max_bytes: Positive
    name_segment_max_bytes: Positive
    name_pattern: str
    media_type_max_bytes: Positive


class Provenance(BaseModel):
    model_config = ConfigDict(strict=True, frozen=True, extra="forbid")
    repository: str
    path: str
    commit: str
    sha256: str


def generate() -> str:
    raw = (ROOT / "contracts/file-limits.json").read_bytes()
    source = Provenance.model_validate(
        tomllib.loads((ROOT / "contracts/FILE_LIMITS_SOURCE.toml").read_text())
    )
    if hashlib.sha256(raw).hexdigest() != source.sha256:
        raise ValueError("canonical file limits differ from their pinned source")
    limits = FileLimits.model_validate_json(raw)
    return (
        "# Generated by scripts/gen_file_limits.py; do not edit.\n"
        f"# Core source: {source.commit}:{source.path}\n"
        f"FILE_LIMITS_SHA256 = {json.dumps(source.sha256)}\n"
        f"FILE_MAX_BYTES = {limits.file_max_bytes}\n"
        f"LAUNCH_MAX_BYTES = {limits.launch_max_bytes}\n"
        f"LAUNCH_MAX_FILES = {limits.launch_max_files}\n"
        f"MANIFEST_MAX_BYTES = {limits.manifest_max_bytes}\n"
        f"INLINE_CONTENT_MAX_BYTES = {limits.inline_content_max_bytes}\n"
        f"NAME_MAX_BYTES = {limits.name_max_bytes}\n"
        f"NAME_SEGMENT_MAX_BYTES = {limits.name_segment_max_bytes}\n"
        f"NAME_PATTERN = {json.dumps(limits.name_pattern)}\n"
        f"MEDIA_TYPE_MAX_BYTES = {limits.media_type_max_bytes}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "synth_ai/_generated/file_limits.py"
    expected = generate()
    if args.check:
        if not path.exists() or path.read_text() != expected:
            raise SystemExit("generated file limits are stale")
    else:
        path.write_text(expected)


if __name__ == "__main__":
    main()
